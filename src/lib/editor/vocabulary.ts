export const tidalCompletion: CompletionSource = (cx: CompletionContext) => {
	const word = cx.matchBefore(/[A-Za-z_][A-Za-z0-9_']*/);
	if (!word?.text && !cx.explicit) return null;
	const prefix = (word?.text ?? '').toLowerCase();
	const options = vocabulary
		.filter((v) => v.label.toLowerCase().startsWith(prefix))
		.slice(0, 120)
		.map((v) => ({ label: v.label, type: v.type, info: v.info }));
	if (options.length === 0) return null;
	return { from: word?.from ?? cx.pos, options };
};
